<script setup>
/**
 * Built on reka-ui ColorSwatch (role="img" labelled with a readable colour name).
 * Sizes: sm (20px), md (32px), lg (48px). Shapes: square, circle.
 * Colours with transparency are drawn over a checkerboard; an empty colour shows a diagonal "none" line.
 *
 * Usage: <ColorSwatch color="#17795a" />
 *        <ColorSwatch color="#17795a80" size="lg" shape="circle" label="Hijau brand 50%" />
 *
 * `color` accepts hex (#rgb, #rrggbb, #rrggbbaa), rgb(), hsl() or hsb() strings.
 * The default slot is rendered centred on top of the colour (e.g. a check icon).
 */
import { ColorSwatch, isValidColor, parseColor } from 'reka-ui';
import { computed } from 'vue';

const props = defineProps({
    color: { type: String, default: '' },
    /** Accessible name; defaults to a colour name generated by reka-ui. */
    label: { type: String, default: undefined },
    size: { type: String, default: 'md' },
    shape: { type: String, default: 'square' },
});

const sizeClasses = {
    sm: 'size-5',
    md: 'size-8',
    lg: 'size-12',
};

const radiusClasses = {
    sm: 'rounded-md',
    md: 'rounded-lg',
    lg: 'rounded-xl',
};

const hasColor = computed(() => isValidColor(props.color) && parseColor(props.color).alpha > 0);

/** The colour itself comes from the `--reka-color-swatch-color` variable that reka-ui sets on the element. */
const backgroundStyle = computed(() =>
    hasColor.value
        ? {
              backgroundImage:
                  'linear-gradient(var(--reka-color-swatch-color), var(--reka-color-swatch-color)), repeating-conic-gradient(#d4d4d4 0 25%, #ffffff 0 50%)',
              backgroundSize: '100% 100%, 10px 10px',
          }
        : {
              backgroundImage:
                  'linear-gradient(to top right, transparent calc(50% - 1px), var(--color-danger) calc(50% - 1px) calc(50% + 1px), transparent calc(50% + 1px))',
          },
);
</script>

<template>
    <ColorSwatch
        :color="color"
        :label="label"
        :style="backgroundStyle"
        :class="[
            'inline-flex shrink-0 items-center justify-center bg-surface shadow-xs inset-ring inset-ring-ink/10',
            sizeClasses[size],
            shape === 'circle' ? 'rounded-full' : radiusClasses[size],
        ]"
    >
        <slot />
    </ColorSwatch>
</template>
